public class Literalpractice {

    public static void main(String[] args) {

        long number = 123456789L;

        float price = 12.5f;

        char symbol = '\u00A9';

        System.out.println("Long value: " + number);
        System.out.println("Float value: " + price);
        System.out.println("Unicode char: " + symbol);
    }
}
